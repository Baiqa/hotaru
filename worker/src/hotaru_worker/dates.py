"""Выбор времени публикации статьи (фаза 3 плана P0).

Аудит 2026-11-11 и проверка 2026-11-15 показали:

- Все ленты RSS отдают полное время публикации (проверено по 10 источникам:
  ни одной полуночной метки, ни одной даты из будущего). Это точный источник.
- Дата со страницы (trafilatura) имеет точность до суток — у 6096 из 6096
  полнотекстовых статей время ровно 00:00 UTC — и нередко просто неверна: у РИА
  встречаются `2023-01-01` и `2026-11-01` для статей, в пути которых стоит
  `/20261115/`. Раньше она перекрывала время из RSS.

Поэтому порядок такой: время из RSS; иначе дата страницы, если она правдоподобна;
иначе момент сбора (статья свежая: она только что появилась в ленте).
"""

from datetime import datetime, timedelta

# Допуск на расхождение часов и часовых поясов: дата чуть позже «сейчас» не ошибка.
FUTURE_TOLERANCE = timedelta(hours=1)

# Дату страницы принимаем, только если она не старше недели. Лента отдаёт свежие
# материалы, поэтому дата страницы месячной давности — почти всегда мусор парсера.
# К времени из RSS это ограничение НЕ применяется: ленты вроде Guardian законно
# держат материалы по 12 дней (проверено), и это настоящая дата публикации.
MAX_PAGE_DATE_AGE = timedelta(days=7)


def choose_published_at(
    rss_time: datetime | None,
    page_date: datetime | None,
    now: datetime,
) -> datetime:
    """Время публикации для записи в БД. Все аргументы — с часовым поясом."""
    if rss_time is not None and rss_time <= now + FUTURE_TOLERANCE:
        return rss_time
    if page_date is not None and now - MAX_PAGE_DATE_AGE <= page_date <= now + FUTURE_TOLERANCE:
        return page_date
    return now
